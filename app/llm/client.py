"""Ollama and Pluggable LLM Client Interfaces.

Provides standard-library HTTP integration with local Ollama runtime (Gemma 3 12B)
and mock doubles for 100% deterministic, offline automated unit tests.
Zero third-party framework dependencies (no LangChain, no LlamaIndex, no heavy wrappers).
"""

from abc import ABC, abstractmethod
import json
import os
import socket
from typing import Any, Callable, Dict, List, Optional
import urllib.error
import urllib.request

from app.core.logging_config import get_logger

logger = get_logger(__name__)

DEFAULT_OLLAMA_BASE_URL = "http://127.0.0.1:11434"
DEFAULT_OLLAMA_MODEL = "gemma3:12b"
DEFAULT_OLLAMA_TIMEOUT_SECONDS = 30.0


class LLMError(RuntimeError):
    """Base exception for all LLM client and inference failures."""
    pass


class LLMClientError(LLMError):
    """Raised when communication with the LLM runtime fails (connection, HTTP, timeout)."""
    pass


class LLMModelUnavailableError(LLMClientError):
    """Raised when the requested model is not installed or available in Ollama."""
    pass


class LLMResponseError(LLMError):
    """Raised when the LLM runtime returns malformed, empty, or unparseable payloads."""
    pass


class BaseLLMClient(ABC):
    """Abstract base class defining the contract for LLM generation backends."""

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Return the unique model identifier (e.g., 'gemma3:12b')."""
        pass

    @abstractmethod
    def is_available(self) -> bool:
        """Check whether the LLM backend is reachable and ready."""
        pass

    @abstractmethod
    def get_status(self) -> Dict[str, Any]:
        """Return structured diagnostic status for health checks and observability."""
        pass

    def check_model_residency(self) -> Optional[bool]:
        """Check whether the model is currently resident/loaded in memory.

        Returns True if loaded, False if not loaded, or None if unknown/unsupported.
        """
        return None

    @abstractmethod
    def generate(
        self,
        prompt: str,
        system: Optional[str] = None,
        format_json: bool = True,
    ) -> str:
        """Generate text from the model given a prompt and optional system instructions.

        Args:
            prompt: User prompt content.
            system: Optional system instruction prompt.
            format_json: If True, instructs the backend to constrain output to valid JSON.

        Returns:
            Raw string generated by the model.

        Raises:
            LLMClientError: If communication or timeout fails.
            LLMModelUnavailableError: If the specified model is not installed.
            LLMResponseError: If response payload is empty or malformed.
        """
        pass


def _match_model_tag(candidate: str, target: str) -> bool:
    """Check whether candidate model tag matches target model tag strictly under Ollama contract.

    Contract Rules:
    1. Case-insensitive exact match.
    2. Optional default registry namespace 'library/' is normalized.
    3. Missing tag canonically defaults to ':latest' (e.g. 'gemma3' == 'gemma3:latest').
    4. Unsafe substring matching is strictly rejected: 'gemma3:12b' does NOT match 'gemma3:12b-instruct'.
    """
    c = str(candidate).strip().lower()
    t = str(target).strip().lower()
    if not c or not t:
        return False
    if c == t:
        return True

    if c.startswith("library/"):
        c = c[len("library/"):]
    if t.startswith("library/"):
        t = t[len("library/"):]
    if c == t:
        return True

    # Normalize canonical implicit ':latest' tag
    c_tag = c if ":" in c else f"{c}:latest"
    t_tag = t if ":" in t else f"{t}:latest"
    return c_tag == t_tag


class OllamaLLMClient(BaseLLMClient):
    """Standard-library HTTP client connecting to local Ollama REST API.

    Adheres to ADR 12 (Provider Agnosticism) and Senior Dev rules by using native
    urllib.request rather than third-party SDKs, keeping the deployment lightweight.
    """

    def __init__(
        self,
        base_url: Optional[str] = None,
        model_name: Optional[str] = None,
        timeout_seconds: Optional[float] = None,
        enabled: Optional[bool] = None,
        http_opener: Optional[Callable[[urllib.request.Request, float], Any]] = None,
    ) -> None:
        """Initialize Ollama client with configurable endpoint and timeout.

        Configuration priority:
        1. Explicit constructor arguments
        2. Environment variables (`OLLAMA_BASE_URL`, `OLLAMA_MODEL`, `OLLAMA_TIMEOUT_SECONDS`, `OLLAMA_ENABLED`)
        3. Built-in defaults (`http://127.0.0.1:11434`, `gemma3:12b`, 30.0s, enabled=True)
        """
        raw_url = base_url or os.environ.get("OLLAMA_BASE_URL", DEFAULT_OLLAMA_BASE_URL)
        self._base_url = raw_url.rstrip("/")
        self._model = (model_name or os.environ.get("OLLAMA_MODEL", DEFAULT_OLLAMA_MODEL)).strip()

        if enabled is not None:
            self._enabled = bool(enabled)
        else:
            env_enabled = os.environ.get("OLLAMA_ENABLED")
            if env_enabled is not None:
                self._enabled = env_enabled.lower() in ("1", "true", "yes", "on")
            else:
                self._enabled = True

        env_timeout = os.environ.get("OLLAMA_TIMEOUT_SECONDS")
        if timeout_seconds is not None:
            self._timeout = float(timeout_seconds)
        elif env_timeout:
            try:
                self._timeout = float(env_timeout)
            except ValueError:
                self._timeout = DEFAULT_OLLAMA_TIMEOUT_SECONDS
        else:
            self._timeout = DEFAULT_OLLAMA_TIMEOUT_SECONDS

        self._http_opener = http_opener or self._default_http_opener

    @property
    def model_name(self) -> str:
        """Return the active model name."""
        return self._model

    @property
    def base_url(self) -> str:
        """Return the Ollama daemon base URL."""
        return self._base_url

    @property
    def is_enabled(self) -> bool:
        """Return True if local Ollama integration is enabled via configuration."""
        return self._enabled

    @property
    def timeout_seconds(self) -> float:
        """Return the configured timeout in seconds."""
        return self._timeout

    def _default_http_opener(self, req: urllib.request.Request, timeout: float) -> Any:
        """Standard library urllib urlopen implementation."""
        return urllib.request.urlopen(req, timeout=timeout)

    def is_available(self) -> bool:
        """Check whether the Ollama daemon is reachable and responding on its API."""
        if not self._enabled:
            return False
        check_url = f"{self._base_url}/api/tags"
        req = urllib.request.Request(check_url, headers={"User-Agent": "StockMarketPrediction/1.0"})
        try:
            with self._http_opener(req, min(self._timeout, 3.0)) as resp:
                return getattr(resp, "status", 200) == 200
        except Exception:
            return False

    def check_model_availability(self) -> bool:
        """Check whether the configured model is installed in local Ollama."""
        if not self._enabled:
            return False
        check_url = f"{self._base_url}/api/tags"
        req = urllib.request.Request(check_url, headers={"User-Agent": "StockMarketPrediction/1.0"})
        try:
            with self._http_opener(req, min(self._timeout, 5.0)) as resp:
                if getattr(resp, "status", 200) != 200:
                    return False
                raw = resp.read().decode("utf-8", errors="replace")
                data = json.loads(raw)
                if not isinstance(data, dict) or "models" not in data or not isinstance(data["models"], list):
                    return False
                for m in data["models"]:
                    if not isinstance(m, dict):
                        continue
                    m_name = m.get("name") or m.get("model")
                    if m_name and _match_model_tag(str(m_name), self._model):
                        return True
                return False
        except Exception:
            return False

    def check_model_residency(self) -> Optional[bool]:
        """Check whether the configured model is currently loaded in memory via /api/ps.

        Distinguishes an installed model from a resident/loaded model.
        Returns:
            True if resident/loaded in memory.
            False if installed but currently idle/unloaded.
            None if residency cannot be determined (e.g. check failed or daemon offline).
        """
        if not self._enabled:
            return False
        check_url = f"{self._base_url}/api/ps"
        req = urllib.request.Request(check_url, headers={"User-Agent": "StockMarketPrediction/1.0"})
        try:
            with self._http_opener(req, min(self._timeout, 3.0)) as resp:
                if getattr(resp, "status", 200) != 200:
                    return None
                raw = resp.read().decode("utf-8", errors="replace")
                data = json.loads(raw)
                if not isinstance(data, dict) or "models" not in data or not isinstance(data["models"], list):
                    return None
                for m in data["models"]:
                    if not isinstance(m, dict):
                        continue
                    m_name = m.get("name") or m.get("model")
                    if m_name and _match_model_tag(str(m_name), self._model):
                        return True
                return False
        except Exception:
            return None

    def get_status(self) -> Dict[str, Any]:
        """Return structured diagnostic status for health checks and observability without exposing secrets."""
        reachable = self.is_available()
        model_ready = self.check_model_availability() if reachable else False
        model_resident = self.check_model_residency() if reachable else None
        return {
            "provider": "ollama",
            "base_url": self._base_url,
            "model": self._model,
            "enabled": self._enabled,
            "reachable": reachable,
            "model_available": model_ready,
            "model_resident": model_resident,
            "timeout_seconds": self._timeout,
        }

    def generate(
        self,
        prompt: str,
        system: Optional[str] = None,
        format_json: bool = True,
    ) -> str:
        """Send completion request to Ollama `/api/generate` endpoint.

        Args:
            prompt: Text prompt for completion.
            system: Optional system instructions.
            format_json: If True, instructs Ollama to enforce valid JSON format.

        Returns:
            String response content.
        """
        if not self._enabled:
            raise LLMClientError("Ollama LLM integration is disabled via configuration (OLLAMA_ENABLED=false)")

        if not prompt or not prompt.strip():
            raise LLMResponseError("Prompt cannot be empty")

        url = f"{self._base_url}/api/generate"
        payload: Dict[str, Any] = {
            "model": self._model,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": 0.1,  # Low temperature for factual, deterministic analysis
            },
        }

        if system:
            payload["system"] = system

        if format_json:
            payload["format"] = "json"

        body_bytes = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=body_bytes,
            headers={
                "Content-Type": "application/json",
                "User-Agent": "StockMarketPrediction/1.0",
            },
            method="POST",
        )

        logger.debug(
            "Dispatching LLM generation request: model=%s, prompt_len=%d, timeout=%.1fs",
            self._model,
            len(prompt),
            self._timeout,
        )

        try:
            with self._http_opener(req, self._timeout) as response:
                status_code = getattr(response, "status", 200)
                if status_code != 200:
                    raise LLMClientError(f"Ollama server returned unexpected status HTTP {status_code}")

                raw_bytes = response.read()
                raw_text = raw_bytes.decode("utf-8", errors="replace")
        except urllib.error.HTTPError as e:
            error_body = ""
            try:
                error_body = e.read().decode("utf-8", errors="replace")[:200]
            except Exception:
                pass
            if e.code == 404 or "not found" in error_body.lower():
                raise LLMModelUnavailableError(
                    f"Model '{self._model}' is not available in Ollama (HTTP {e.code}): {error_body}"
                ) from e
            raise LLMClientError(
                f"Ollama HTTP error {e.code} for model '{self._model}': {e.reason} ({error_body})"
            ) from e
        except (urllib.error.URLError, socket.timeout, TimeoutError) as e:
            raise LLMClientError(
                f"Failed to communicate with Ollama service at '{self._base_url}': {e}"
            ) from e
        except Exception as e:
            raise LLMClientError(f"Unexpected error communicating with Ollama: {e}") from e

        if not raw_text or not raw_text.strip():
            raise LLMResponseError("Ollama returned an empty response body")

        try:
            data = json.loads(raw_text)
        except json.JSONDecodeError as e:
            raise LLMResponseError(f"Ollama response could not be parsed as JSON: {e}") from e

        if not isinstance(data, dict):
            raise LLMResponseError("Ollama payload is not a valid JSON object")

        response_text = data.get("response")
        if response_text is None or not str(response_text).strip():
            # Check for error field returned by Ollama
            if "error" in data:
                err_msg = str(data["error"])
                if "not found" in err_msg.lower():
                    raise LLMModelUnavailableError(f"Ollama engine returned error: {err_msg}")
                raise LLMClientError(f"Ollama engine returned error: {err_msg}")
            raise LLMResponseError("Ollama payload missing non-empty 'response' field")

        return str(response_text).strip()


class MockLLMClient(BaseLLMClient):
    """Deterministic, offline mock client for automated testing and CI.

    Permits testing all prompt assembly, schema parsing, and failure branches
    without starting Ollama or downloading model weights.
    """

    def __init__(
        self,
        model_name: str = "gemma3:12b",
        default_response: Optional[str] = None,
        responses: Optional[Dict[str, str]] = None,
        responder: Optional[Callable[[str, Optional[str]], str]] = None,
        simulated_error: Optional[Exception] = None,
        enabled: bool = True,
    ) -> None:
        """Initialize mock client with pre-configured responses or simulated errors."""
        self._model = model_name
        self._default_response = default_response or "{}"
        self._responses = responses or {}
        self._responder = responder
        self._simulated_error = simulated_error
        self._enabled = enabled
        self.calls: List[Dict[str, Any]] = []

    @property
    def model_name(self) -> str:
        """Return the mock model name."""
        return self._model

    def is_available(self) -> bool:
        """Check whether mock backend is available."""
        return self._enabled and self._simulated_error is None

    def check_model_availability(self) -> bool:
        """Check whether mock model is available."""
        return self._enabled and not isinstance(self._simulated_error, LLMModelUnavailableError)

    def check_model_residency(self) -> Optional[bool]:
        """Mock residency check returns True if enabled and available."""
        return self._enabled and self._simulated_error is None

    def get_status(self) -> Dict[str, Any]:
        """Return structured diagnostic status."""
        return {
            "provider": "mock",
            "base_url": "mock://localhost",
            "model": self._model,
            "enabled": self._enabled,
            "reachable": self.is_available(),
            "model_available": self.check_model_availability(),
            "model_resident": self.check_model_residency(),
            "timeout_seconds": 0.0,
        }

    def generate(
        self,
        prompt: str,
        system: Optional[str] = None,
        format_json: bool = True,
    ) -> str:
        """Return programmed response or trigger simulated exception."""
        if not self._enabled:
            raise LLMClientError("Ollama LLM integration is disabled via configuration (OLLAMA_ENABLED=false)")

        self.calls.append({
            "prompt": prompt,
            "system": system,
            "format_json": format_json,
        })

        if self._simulated_error:
            raise self._simulated_error

        if self._responder:
            return self._responder(prompt, system)

        for trigger_key, response_val in self._responses.items():
            if trigger_key in prompt or (system and trigger_key in system):
                return response_val

        return self._default_response
