"""Canonical LLM Schema Contracts.

Defines standardized, immutable data contracts for structured context extraction
and qualitative financial reasoning generated by the contextual LLM layer (Gemma 3 12B).
Enforces validation, timezone awareness, source attribution, and explicit separation
between qualitative text reasoning and authoritative quantitative machine learning outputs.
"""

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional, Sequence, Tuple

from app.core.schemas import ValidationError

NON_PREDICTIVE_QUALITATIVE_DISCLAIMER = (
    "Qualitative reasoning output based strictly on provided point-in-time context. "
    "Does not assert factual certainty, numerical price targets, calibrated probabilities, "
    "or financial advice."
)


class LLMDirection(str, Enum):
    """Categorical qualitative directional assessment generated by LLM reasoning."""

    UP = "UP"
    DOWN = "DOWN"
    NEUTRAL = "NEUTRAL"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"


def _normalize_string_tuple(items: Any, field_name: str) -> Tuple[str, ...]:
    """Normalize and validate a sequence of strings into an immutable tuple."""
    if items is None:
        return ()
    if isinstance(items, (list, tuple, set)):
        result = []
        for x in items:
            if isinstance(x, str):
                cleaned = x.strip()
                if cleaned:
                    result.append(cleaned)
            elif x is not None:
                cleaned = str(x).strip()
                if cleaned:
                    result.append(cleaned)
        return tuple(result)
    raise ValidationError(f"{field_name} must be a sequence of strings")


@dataclass(frozen=True)
class LLMContextExtraction:
    """Structured extraction of entities, factors, and sector exposures from qualitative sources.

    Represents Role A output: parses unstructured announcements, news, and regulatory notices
    into structured entities and macroeconomic/regulatory factors with explicit source references.
    """

    entities: Tuple[str, ...] = field(default_factory=tuple)
    affected_sectors: Tuple[str, ...] = field(default_factory=tuple)
    macro_factors: Tuple[str, ...] = field(default_factory=tuple)
    regulatory_factors: Tuple[str, ...] = field(default_factory=tuple)
    sentiment_tone: str = "NEUTRAL"
    source_references: Tuple[str, ...] = field(default_factory=tuple)
    uncertainty_notes: Optional[str] = None
    model_version: str = "gemma3:12b"
    extracted_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    raw_response: Optional[str] = None

    def __post_init__(self) -> None:
        # Normalize string tuples
        object.__setattr__(self, "entities", _normalize_string_tuple(self.entities, "entities"))
        object.__setattr__(
            self,
            "affected_sectors",
            tuple(s.upper() for s in _normalize_string_tuple(self.affected_sectors, "affected_sectors")),
        )
        object.__setattr__(self, "macro_factors", _normalize_string_tuple(self.macro_factors, "macro_factors"))
        object.__setattr__(
            self, "regulatory_factors", _normalize_string_tuple(self.regulatory_factors, "regulatory_factors")
        )
        object.__setattr__(
            self, "source_references", _normalize_string_tuple(self.source_references, "source_references")
        )

        # Validate sentiment tone
        if not self.sentiment_tone or not str(self.sentiment_tone).strip():
            object.__setattr__(self, "sentiment_tone", "NEUTRAL")
        else:
            object.__setattr__(self, "sentiment_tone", str(self.sentiment_tone).strip().upper())

        # Validate model version
        if not self.model_version or not self.model_version.strip():
            raise ValidationError("model_version cannot be empty")
        object.__setattr__(self, "model_version", self.model_version.strip())

        # Validate extracted_at timestamp
        if not isinstance(self.extracted_at, datetime):
            raise ValidationError("extracted_at must be a valid datetime instance")
        if self.extracted_at.tzinfo is None:
            raise ValidationError("extracted_at must be timezone-aware")

        # Normalize uncertainty notes
        if self.uncertainty_notes is not None:
            notes_str = str(self.uncertainty_notes).strip()
            object.__setattr__(self, "uncertainty_notes", notes_str if notes_str else None)

    def to_dict(self) -> Dict[str, Any]:
        """Convert context extraction record to dictionary."""
        return {
            "entities": list(self.entities),
            "affected_sectors": list(self.affected_sectors),
            "macro_factors": list(self.macro_factors),
            "regulatory_factors": list(self.regulatory_factors),
            "sentiment_tone": self.sentiment_tone,
            "source_references": list(self.source_references),
            "uncertainty_notes": self.uncertainty_notes,
            "model_version": self.model_version,
            "extracted_at": self.extracted_at.isoformat(),
            "raw_response": self.raw_response,
        }


@dataclass(frozen=True)
class LLMReasoningResult:
    """Canonical representation of qualitative directional reasoning and risk assessment.

    Represents Role B output: an independent, non-authoritative qualitative assessment
    citiing explicit source references, identifying upside/downside factors, and highlighting
    risk elements without modifying quantitative machine learning outputs or fabricating targets.
    """

    symbol: str
    direction: LLMDirection
    reasoning_summary: str
    positive_factors: Tuple[str, ...] = field(default_factory=tuple)
    negative_factors: Tuple[str, ...] = field(default_factory=tuple)
    downside_risks: Tuple[str, ...] = field(default_factory=tuple)
    source_references: Tuple[str, ...] = field(default_factory=tuple)
    confidence_assessment: str = "LOW"
    model_version: str = "gemma3:12b"
    generated_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    disclaimer: str = NON_PREDICTIVE_QUALITATIVE_DISCLAIMER
    raw_response: Optional[str] = None

    def __post_init__(self) -> None:
        # Validate symbol
        if not self.symbol or not self.symbol.strip():
            raise ValidationError("symbol cannot be empty")
        clean_sym = self.symbol.strip().upper()
        if clean_sym.endswith(".NS") or clean_sym.endswith(".BO"):
            clean_sym = clean_sym.rsplit(".", 1)[0]
        object.__setattr__(self, "symbol", clean_sym)

        # Validate direction enum
        if isinstance(self.direction, str):
            try:
                object.__setattr__(self, "direction", LLMDirection(self.direction.strip().upper()))
            except ValueError:
                raise ValidationError(
                    f"Invalid LLMDirection: '{self.direction}'. Must be one of {[d.value for d in LLMDirection]}"
                )
        elif not isinstance(self.direction, LLMDirection):
            raise ValidationError("direction must be an instance of LLMDirection enum")

        # Validate reasoning summary
        if not self.reasoning_summary or not self.reasoning_summary.strip():
            raise ValidationError("reasoning_summary cannot be empty")
        object.__setattr__(self, "reasoning_summary", self.reasoning_summary.strip())

        # Normalize string tuples
        object.__setattr__(self, "positive_factors", _normalize_string_tuple(self.positive_factors, "positive_factors"))
        object.__setattr__(self, "negative_factors", _normalize_string_tuple(self.negative_factors, "negative_factors"))
        object.__setattr__(self, "downside_risks", _normalize_string_tuple(self.downside_risks, "downside_risks"))
        object.__setattr__(
            self, "source_references", _normalize_string_tuple(self.source_references, "source_references")
        )

        # Validate confidence assessment (purely qualitative, e.g. LOW / MEDIUM / HIGH)
        if not self.confidence_assessment or not str(self.confidence_assessment).strip():
            object.__setattr__(self, "confidence_assessment", "LOW")
        else:
            object.__setattr__(self, "confidence_assessment", str(self.confidence_assessment).strip().upper())

        # Validate model version
        if not self.model_version or not self.model_version.strip():
            raise ValidationError("model_version cannot be empty")
        object.__setattr__(self, "model_version", self.model_version.strip())

        # Validate generation timestamp
        if not isinstance(self.generated_at, datetime):
            raise ValidationError("generated_at must be a valid datetime instance")
        if self.generated_at.tzinfo is None:
            raise ValidationError("generated_at must be timezone-aware")

        # Ensure disclaimer is preserved
        if not self.disclaimer or not self.disclaimer.strip():
            object.__setattr__(self, "disclaimer", NON_PREDICTIVE_QUALITATIVE_DISCLAIMER)

    def to_dict(self) -> Dict[str, Any]:
        """Convert reasoning result to dictionary."""
        return {
            "symbol": self.symbol,
            "direction": self.direction.value,
            "reasoning_summary": self.reasoning_summary,
            "positive_factors": list(self.positive_factors),
            "negative_factors": list(self.negative_factors),
            "downside_risks": list(self.downside_risks),
            "source_references": list(self.source_references),
            "confidence_assessment": self.confidence_assessment,
            "model_version": self.model_version,
            "generated_at": self.generated_at.isoformat(),
            "disclaimer": self.disclaimer,
            "raw_response": self.raw_response,
        }

    def to_explanation(
        self,
        status: "LLMExplanationStatus" = None,
    ) -> "LLMExplanationResult":
        """Adapt LLMReasoningResult to canonical LLMExplanationResult."""
        stat = status or LLMExplanationStatus.SUCCESS
        evidence = list(self.source_references)
        for f in self.positive_factors:
            if f not in evidence:
                evidence.append(f)
        for f in self.negative_factors:
            if f not in evidence:
                evidence.append(f)
        return LLMExplanationResult(
            status=stat,
            summary=self.reasoning_summary,
            supporting_evidence=tuple(evidence),
            limitations=self.downside_risks,
            model=self.model_version,
            generated_at=self.generated_at.isoformat(),
            symbol=self.symbol,
            direction=self.direction.value,
            confidence=self.confidence_assessment,
            disclaimer=self.disclaimer,
            raw_response=self.raw_response,
        )


class LLMExplanationStatus(str, Enum):
    """Operational status of qualitative prediction explanation generation."""

    SUCCESS = "SUCCESS"
    NO_CONTEXT = "NO_CONTEXT"
    UNAVAILABLE = "UNAVAILABLE"
    DISABLED = "DISABLED"
    TIMEOUT = "TIMEOUT"
    FAILED = "FAILED"


@dataclass(frozen=True)
class LLMExplanationResult:
    """Canonical representation of an evidence-grounded qualitative prediction explanation.

    Synthesizes point-in-time financial news and regulatory events to explain quantitative forecasts
    without altering numerical prediction probabilities, directions, or target prices.
    """

    status: LLMExplanationStatus
    summary: str
    supporting_evidence: Tuple[str, ...] = field(default_factory=tuple)
    limitations: Tuple[str, ...] = field(default_factory=tuple)
    model: str = "gemma3:12b"
    generated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    symbol: Optional[str] = None
    direction: Optional[str] = None
    confidence: Optional[str] = None
    disclaimer: str = NON_PREDICTIVE_QUALITATIVE_DISCLAIMER
    raw_response: Optional[str] = None

    def __post_init__(self) -> None:
        if isinstance(self.status, str):
            try:
                object.__setattr__(self, "status", LLMExplanationStatus(self.status.strip().upper()))
            except ValueError:
                object.__setattr__(self, "status", LLMExplanationStatus.FAILED)
        elif not isinstance(self.status, LLMExplanationStatus):
            raise ValidationError("status must be an instance of LLMExplanationStatus")

        if not self.summary or not str(self.summary).strip():
            object.__setattr__(self, "summary", "No qualitative summary generated.")
        else:
            object.__setattr__(self, "summary", str(self.summary).strip())

        object.__setattr__(
            self,
            "supporting_evidence",
            _normalize_string_tuple(self.supporting_evidence, "supporting_evidence"),
        )
        object.__setattr__(
            self,
            "limitations",
            _normalize_string_tuple(self.limitations, "limitations"),
        )

        if not self.model or not str(self.model).strip():
            object.__setattr__(self, "model", "gemma3:12b")
        else:
            object.__setattr__(self, "model", str(self.model).strip())

        if self.symbol:
            clean_sym = str(self.symbol).strip().upper()
            if clean_sym.endswith(".NS") or clean_sym.endswith(".BO"):
                clean_sym = clean_sym.rsplit(".", 1)[0]
            object.__setattr__(self, "symbol", clean_sym)

        if self.direction:
            object.__setattr__(self, "direction", str(self.direction).strip().upper())

        if self.confidence:
            object.__setattr__(self, "confidence", str(self.confidence).strip().upper())
        else:
            object.__setattr__(self, "confidence", "LOW")

        if not self.disclaimer or not str(self.disclaimer).strip():
            object.__setattr__(self, "disclaimer", NON_PREDICTIVE_QUALITATIVE_DISCLAIMER)

    def to_dict(self) -> Dict[str, Any]:
        """Convert explanation result to canonical dictionary."""
        return {
            "status": self.status.value,
            "summary": self.summary,
            "supporting_evidence": list(self.supporting_evidence),
            "limitations": list(self.limitations),
            "model": self.model,
            "generated_at": self.generated_at,
            "symbol": self.symbol,
            "direction": self.direction,
            "confidence": self.confidence,
            "disclaimer": self.disclaimer,
            "raw_response": self.raw_response,
        }

    def to_reasoning_result(self) -> LLMReasoningResult:
        """Convert successful explanation into standard LLMReasoningResult for ensemble synthesis."""
        dir_val = LLMDirection.INSUFFICIENT_EVIDENCE
        if self.direction:
            try:
                dir_val = LLMDirection(self.direction.upper())
            except ValueError:
                dir_val = LLMDirection.INSUFFICIENT_EVIDENCE

        pos_factors = tuple(
            e for e in self.supporting_evidence
            if any(w in e.lower() for w in ("positive", "gain", "growth", "support", "upside", "expansion"))
        ) or self.supporting_evidence

        neg_factors = tuple(
            e for e in self.supporting_evidence
            if any(w in e.lower() for w in ("negative", "loss", "decline", "risk", "downside", "penalty", "adverse"))
        )

        return LLMReasoningResult(
            symbol=self.symbol or "UNKNOWN",
            direction=dir_val,
            reasoning_summary=self.summary,
            positive_factors=pos_factors,
            negative_factors=neg_factors,
            downside_risks=self.limitations,
            source_references=self.supporting_evidence,
            confidence_assessment=self.confidence or "LOW",
            model_version=self.model,
            disclaimer=self.disclaimer,
            raw_response=self.raw_response,
        )

    @classmethod
    def no_context(cls, symbol: str, model: str = "gemma3:12b") -> "LLMExplanationResult":
        """Factory for empty point-in-time context."""
        return cls(
            status=LLMExplanationStatus.NO_CONTEXT,
            summary="No verified point-in-time news or regulatory events available within the lookback window.",
            supporting_evidence=(),
            limitations=("No external contextual records met point-in-time filters as of the prediction cutoff.",),
            model=model,
            symbol=symbol,
            direction=LLMDirection.INSUFFICIENT_EVIDENCE.value,
            confidence="LOW",
        )

    @classmethod
    def disabled(cls, symbol: str, model: str = "gemma3:12b") -> "LLMExplanationResult":
        """Factory for disabled LLM configuration."""
        return cls(
            status=LLMExplanationStatus.DISABLED,
            summary="Local LLM service is disabled by configuration (OLLAMA_ENABLED=False).",
            supporting_evidence=(),
            limitations=("Qualitative LLM explanation was skipped by administrative configuration.",),
            model=model,
            symbol=symbol,
            direction=LLMDirection.INSUFFICIENT_EVIDENCE.value,
            confidence="LOW",
        )

    @classmethod
    def unavailable(
        cls,
        symbol: str,
        model: str = "gemma3:12b",
        reason: str = "Local LLM service or model is unavailable.",
    ) -> "LLMExplanationResult":
        """Factory for unavailable local Ollama daemon or model."""
        return cls(
            status=LLMExplanationStatus.UNAVAILABLE,
            summary=f"Local LLM service is unavailable: {reason}",
            supporting_evidence=(),
            limitations=(reason,),
            model=model,
            symbol=symbol,
            direction=LLMDirection.INSUFFICIENT_EVIDENCE.value,
            confidence="LOW",
        )

    @classmethod
    def timeout(cls, symbol: str, model: str = "gemma3:12b") -> "LLMExplanationResult":
        """Factory for request timeout."""
        return cls(
            status=LLMExplanationStatus.TIMEOUT,
            summary="Local LLM explanation request timed out before receiving a response.",
            supporting_evidence=(),
            limitations=("Inference exceeded configured OLLAMA_TIMEOUT_SECONDS.",),
            model=model,
            symbol=symbol,
            direction=LLMDirection.INSUFFICIENT_EVIDENCE.value,
            confidence="LOW",
        )

    @classmethod
    def failed(
        cls,
        symbol: str,
        model: str = "gemma3:12b",
        error_message: str = "LLM explanation generation failed.",
    ) -> "LLMExplanationResult":
        """Factory for generation or parsing failures."""
        return cls(
            status=LLMExplanationStatus.FAILED,
            summary="Qualitative explanation could not be generated from market context.",
            supporting_evidence=(),
            limitations=(error_message,),
            model=model,
            symbol=symbol,
            direction=LLMDirection.INSUFFICIENT_EVIDENCE.value,
            confidence="LOW",
        )
