logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class FoldErrorAnalysis:
    """Detailed error and distribution shift diagnostics for a fold-strategy evaluation."""

    fold: int
    strategy_name: str
    train_rows: int
    val_rows: int
    train_up_count: int
    train_down_count: int
    train_up_ratio: float
    val_up_count: int
    val_down_count: int
    val_up_ratio: float
    distribution_shift_up: float  # val_up_ratio - train_up_ratio
    accuracy: Optional[float]
    majority_accuracy: Optional[float]
    diff_vs_majority: Optional[float]  # accuracy - majority_accuracy
    precision_up: Optional[float]
    recall_up: Optional[float]
    f1_up: Optional[float]
    precision_down: Optional[float]
    recall_down: Optional[float]
    f1_down: Optional[float]
    confusion_matrix: Optional[List[List[int]]]
    tp: int
    fp: int
    fn: int
    tn: int
    pred_up_count: int
    pred_down_count: int
    is_systematic_direction: bool
    systematic_direction: Optional[str]  # "ALL_UP", "ALL_DOWN", or None
    status: str = "COMPLETED"
    skip_reason: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Serialize fold error analysis to dict."""
        return {
            "fold": self.fold,
            "strategy_name": self.strategy_name,
            "train_rows": self.train_rows,
            "val_rows": self.val_rows,
            "train_up_ratio": self.train_up_ratio,
            "val_up_ratio": self.val_up_ratio,
            "distribution_shift_up": self.distribution_shift_up,
            "accuracy": self.accuracy,
            "majority_accuracy": self.majority_accuracy,
            "diff_vs_majority": self.diff_vs_majority,
            "precision_up": self.precision_up,
            "recall_up": self.recall_up,
            "f1_up": self.f1_up,
            "precision_down": self.precision_down,
            "recall_down": self.recall_down,
            "f1_down": self.f1_down,
            "confusion_matrix": self.confusion_matrix,
            "tp": self.tp,
            "fp": self.fp,
            "fn": self.fn,
            "tn": self.tn,
            "pred_up_count": self.pred_up_count,
            "pred_down_count": self.pred_down_count,
            "is_systematic_direction": self.is_systematic_direction,
            "systematic_direction": self.systematic_direction,
            "status": self.status,
            "skip_reason": self.skip_reason,
        }


def analyze_walk_forward_errors(report: WalkForwardReport) -> List[FoldErrorAnalysis]:
    """Decompose walk-forward cross-validation results into detailed error diagnostics.

    Computes for every fold and strategy:
    - Symmetrical UP and DOWN class metrics (accuracy, precision, recall, F1).
    - True positive / false positive / false negative / true negative counts.
    - Actual vs predicted class distribution.
    - Distribution shift between training partition and validation fold.
    - Directional bias detection (e.g. predicting all UP or all DOWN).
    - Accuracy margin relative to the Majority Class baseline.

    Args:
        report: WalkForwardReport generated by run_walk_forward_evaluation.

    Returns:
        List of FoldErrorAnalysis instances.
    """
    # Map fold index to fold split
    split_by_fold: Dict[int, WalkForwardFoldSplit] = {f.fold: f for f in report.folds}

    # Find majority class baseline accuracy per fold
    majority_acc_by_fold: Dict[int, Optional[float]] = {}
    for ev in report.fold_evaluations:
        if "Majority Class" in ev.strategy_name and ev.status == "COMPLETED" and ev.metrics:
            majority_acc_by_fold[ev.fold] = ev.metrics.accuracy

    results: List[FoldErrorAnalysis] = []
    for ev in report.fold_evaluations:
        split = split_by_fold.get(ev.fold)
        if split is None:
            continue

        train_up = split.train_up_count
        train_down = split.train_down_count
        train_ratio = split.train_up_ratio
        val_up = split.val_up_count
        val_down = split.val_down_count
        val_ratio = split.val_up_ratio
        dist_shift = round(val_ratio - train_ratio, 4)

        if ev.status != "COMPLETED" or ev.metrics is None:
            results.append(
                FoldErrorAnalysis(
                    fold=ev.fold,
                    strategy_name=ev.strategy_name,
                    train_rows=split.train_rows,
                    val_rows=split.val_rows,
                    train_up_count=train_up,
                    train_down_count=train_down,
                    train_up_ratio=train_ratio,
                    val_up_count=val_up,
                    val_down_count=val_down,
                    val_up_ratio=val_ratio,
                    distribution_shift_up=dist_shift,
                    accuracy=None,
                    majority_accuracy=majority_acc_by_fold.get(ev.fold),
                    diff_vs_majority=None,
                    precision_up=None,
                    recall_up=None,
                    f1_up=None,
                    precision_down=None,
                    recall_down=None,
                    f1_down=None,
                    confusion_matrix=None,
                    tp=0,
                    fp=0,
                    fn=0,
                    tn=0,
                    pred_up_count=ev.pred_up_count,
                    pred_down_count=ev.pred_down_count,
                    is_systematic_direction=False,
                    systematic_direction=None,
                    status=ev.status,
                    skip_reason=ev.skip_reason,
                )
            )
            continue

        m = ev.metrics
        acc = m.accuracy
        maj_acc = majority_acc_by_fold.get(ev.fold)
        diff_maj = round(acc - maj_acc, 4) if maj_acc is not None else None

        # Symmetrical DOWN metrics from ClassificationMetrics or computed
        prec_down = m.precision_down
        rec_down = m.recall_down
        f1_down = m.f1_down

        # Directional prediction bias detection
        total_pred = ev.pred_up_count + ev.pred_down_count
        is_systematic = (ev.pred_up_count == 0 or ev.pred_down_count == 0) and total_pred > 0
        systematic_dir: Optional[str] = None
        if is_systematic:
            systematic_dir = "ALL_UP" if ev.pred_down_count == 0 else "ALL_DOWN"

        results.append(
            FoldErrorAnalysis(
                fold=ev.fold,
                strategy_name=ev.strategy_name,
                train_rows=split.train_rows,
                val_rows=split.val_rows,
                train_up_count=train_up,
                train_down_count=train_down,
                train_up_ratio=train_ratio,
                val_up_count=val_up,
                val_down_count=val_down,
                val_up_ratio=val_ratio,
                distribution_shift_up=dist_shift,
                accuracy=acc,
                majority_accuracy=maj_acc,
                diff_vs_majority=diff_maj,
                precision_up=m.precision,
                recall_up=m.recall,
                f1_up=m.f1,
                precision_down=prec_down,
                recall_down=rec_down,
                f1_down=f1_down,
                confusion_matrix=m.confusion_matrix,
                tp=m.true_positives,
                fp=m.false_positives,
                fn=m.false_negatives,
                tn=m.true_negatives,
                pred_up_count=ev.pred_up_count,
                pred_down_count=ev.pred_down_count,
                is_systematic_direction=is_systematic,
                systematic_direction=systematic_dir,
                status="COMPLETED",
                skip_reason=None,
            )
        )

    return results


@dataclass(frozen=True)
class FeatureQualityMetric:
    """Summary statistics and data health for a single feature."""

    feature_name: str
    missing_count: int
    missing_ratio: float
    is_constant: bool
    unique_count: int
    mean: float
    std: float
    min_val: float
    max_val: float


@dataclass(frozen=True)
class HighCorrelationPair:
    """Pair of features with Pearson absolute correlation exceeding threshold."""

    feature_a: str
    feature_b: str
    correlation: float


@dataclass(frozen=True)
class FeatureUsefulnessAudit:
    """Comprehensive feature matrix quality and exploratory importance audit.

    All statistics and importance values are computed strictly on training data
    to guarantee zero lookahead leakage into validation or test folds.
    """

    n_samples: int
    n_features: int
    feature_metrics: Dict[str, FeatureQualityMetric]
    constant_features: List[str]
    missing_features: List[str]
    high_correlation_pairs: List[HighCorrelationPair]
    correlation_threshold: float
    xgboost_importances: Optional[Dict[str, float]] = None
    lightgbm_importances: Optional[Dict[str, float]] = None
    top_xgboost_features: List[Tuple[str, float]] = field(default_factory=list)
    top_lightgbm_features: List[Tuple[str, float]] = field(default_factory=list)
    zero_importance_xgboost: List[str] = field(default_factory=list)
    zero_importance_lightgbm: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        """Serialize audit results."""
        return {
            "n_samples": self.n_samples,
            "n_features": self.n_features,
            "constant_features": self.constant_features,
            "missing_features": self.missing_features,
            "high_correlation_pairs_count": len(self.high_correlation_pairs),
            "correlation_threshold": self.correlation_threshold,
            "top_xgboost_features": self.top_xgboost_features[:10],
            "top_lightgbm_features": self.top_lightgbm_features[:10],
            "zero_importance_xgboost": self.zero_importance_xgboost,
            "zero_importance_lightgbm": self.zero_importance_lightgbm,
        }


def audit_feature_usefulness(
    X_train: pd.DataFrame,
    xgboost_model: Optional[Any] = None,
    lightgbm_model: Optional[Any] = None,
    correlation_threshold: float = 0.90,
) -> FeatureUsefulnessAudit:
    """Audit feature matrix quality, collinearity, and tree model importance.

    Strict Invariants:
    1. Isolation Guard: Validates that X_train contains no target or outcome columns.
    2. Zero Leakage: All diagnostics (mean, std, missingness, correlation, importances)
       are computed solely on the supplied training data partition.
    3. Exploratory Importance: Tree split/weight counts are treated as exploratory
       model properties, not causal proof of predictive signal.

    Args:
        X_train: Training feature matrix (pandas DataFrame).
        xgboost_model: Optional fitted XGBoostDirectionClassifier.
        lightgbm_model: Optional fitted LightGBMDirectionClassifier.
        correlation_threshold: Pearson correlation cutoff for identifying collinear pairs (default 0.90).

    Returns:
        FeatureUsefulnessAudit instance.

    Raises:
        ValueError: If X_train contains target/outcome columns, is empty, or has no features.
    """
    if X_train.empty:
        raise ValueError("Cannot audit empty feature matrix.")
    if X_train.shape[1] == 0:
        raise ValueError("Feature matrix has 0 columns.")

    # Isolation Guard: raises ValueError if target or outcome columns are present
    validate_feature_matrix_isolation(X_train)

    n_samples, n_features = X_train.shape
    feature_metrics: Dict[str, FeatureQualityMetric] = {}
    constant_features: List[str] = []
    missing_features: List[str] = []

    for col in X_train.columns:
        s = X_train[col]
        missing_cnt = int(s.isna().sum())
        missing_rat = round(missing_cnt / n_samples, 4)
        if missing_cnt > 0:
            missing_features.append(str(col))

        valid_s = s.dropna()
        n_unique = int(valid_s.nunique())
        mean_val = round(float(valid_s.mean()), 6) if not valid_s.empty else 0.0
        std_val = round(float(valid_s.std()), 6) if len(valid_s) > 1 else 0.0
        min_v = round(float(valid_s.min()), 6) if not valid_s.empty else 0.0
        max_v = round(float(valid_s.max()), 6) if not valid_s.empty else 0.0

        is_const = bool(n_unique <= 1 or (len(valid_s) > 1 and std_val == 0.0))
        if is_const:
            constant_features.append(str(col))

        feature_metrics[str(col)] = FeatureQualityMetric(
            feature_name=str(col),
            missing_count=missing_cnt,
            missing_ratio=missing_rat,
            is_constant=is_const,
            unique_count=n_unique,
            mean=mean_val,
            std=std_val,
            min_val=min_v,
            max_val=max_v,
        )

    # Collinearity Analysis via Pearson Correlation Matrix
    corr_df = X_train.corr(method="pearson").fillna(0.0)
    high_corr_pairs: List[HighCorrelationPair] = []
    cols = list(X_train.columns)
    for i in range(len(cols)):
        for j in range(i + 1, len(cols)):
            col_a, col_b = cols[i], cols[j]
            r = float(corr_df.iloc[i, j])
            if abs(r) >= correlation_threshold:
                high_corr_pairs.append(
                    HighCorrelationPair(
                        feature_a=str(col_a),
                        feature_b=str(col_b),
                        correlation=round(r, 4),
                    )
                )

    # Sort correlation pairs by absolute correlation descending
    high_corr_pairs.sort(key=lambda p: abs(p.correlation), reverse=True)

    # XGBoost Importance Extraction
    xgb_imp: Optional[Dict[str, float]] = None
    top_xgb: List[Tuple[str, float]] = []
    zero_xgb: List[str] = []
    if xgboost_model is not None and getattr(xgboost_model, "is_fitted", False):
        try:
            raw_imp = xgboost_model.feature_importances_
            xgb_imp = {k: float(v) for k, v in raw_imp.items()}
            sorted_xgb = sorted(xgb_imp.items(), key=lambda x: x[1], reverse=True)
            top_xgb = sorted_xgb
            zero_xgb = [k for k, v in sorted_xgb if v == 0.0]
        except Exception as exc:
            logger.warning("Failed to extract XGBoost feature importances: %s", exc)

    # LightGBM Importance Extraction
    lgb_imp: Optional[Dict[str, float]] = None
    top_lgb: List[Tuple[str, float]] = []
    zero_lgb: List[str] = []
    if lightgbm_model is not None and getattr(lightgbm_model, "is_fitted", False):
        try:
            raw_imp = lightgbm_model.feature_importances_
            lgb_imp = {k: float(v) for k, v in raw_imp.items()}
            sorted_lgb = sorted(lgb_imp.items(), key=lambda x: x[1], reverse=True)
            top_lgb = sorted_lgb
            zero_lgb = [k for k, v in sorted_lgb if v == 0.0]
        except Exception as exc:
            logger.warning("Failed to extract LightGBM feature importances: %s", exc)

    return FeatureUsefulnessAudit(
        n_samples=n_samples,
        n_features=n_features,
        feature_metrics=feature_metrics,
        constant_features=constant_features,
        missing_features=missing_features,
        high_correlation_pairs=high_corr_pairs,
        correlation_threshold=correlation_threshold,
        xgboost_importances=xgb_imp,
        lightgbm_importances=lgb_imp,
        top_xgboost_features=top_xgb,
        top_lightgbm_features=top_lgb,
        zero_importance_xgboost=zero_xgb,
        zero_importance_lightgbm=zero_lgb,
    )


def render_fold_error_table(
    analyses: Sequence[FoldErrorAnalysis],
    strategy_filter: Optional[str] = None,
) -> str:
    """Format per-fold error and class breakdown as a Markdown table."""
    headers = [
        "Fold",
        "Strategy",
        "Train UP%",
        "Val UP%",
        "Shift",
        "Acc",
        "Maj Acc",
        "Diff Maj",
        "UP (P/R/F1)",
        "DN (P/R/F1)",
        "Pred UP/DN",
        "CM [TN,FP/FN,TP]",
        "Bias",
    ]
    rows = []
    for a in analyses:
        if strategy_filter and strategy_filter not in a.strategy_name:
            continue
        if a.status != "COMPLETED":
            rows.append(
                f"| {a.fold} | {a.strategy_name[:20]} | {a.train_up_ratio*100:.1f}% | "
                f"{a.val_up_ratio*100:.1f}% | {a.distribution_shift_up*100:+.1f}% | "
                f"SKIP | - | - | - | - | - | - | {a.skip_reason or 'SKIPPED'} |"
            )
            continue

        acc_str = f"{a.accuracy*100:.1f}%" if a.accuracy is not None else "-"
        maj_str = f"{a.majority_accuracy*100:.1f}%" if a.majority_accuracy is not None else "-"
        diff_str = f"{a.diff_vs_majority*100:+.1f}%" if a.diff_vs_majority is not None else "-"

        up_str = f"{a.precision_up*100:.0f}/{a.recall_up*100:.0f}/{a.f1_up*100:.0f}" if a.precision_up is not None else "-"
        dn_str = f"{a.precision_down*100:.0f}/{a.recall_down*100:.0f}/{a.f1_down*100:.0f}" if a.precision_down is not None else "-"
        pred_str = f"{a.pred_up_count}/{a.pred_down_count}"
        cm_str = f"[{a.tn},{a.fp}/{a.fn},{a.tp}]"
        bias_str = a.systematic_direction if a.is_systematic_direction else "No"

        rows.append(
            f"| {a.fold} | {a.strategy_name[:20]} | {a.train_up_ratio*100:.1f}% | "
            f"{a.val_up_ratio*100:.1f}% | {a.distribution_shift_up*100:+.1f}% | "
            f"{acc_str} | {maj_str} | {diff_str} | {up_str} | {dn_str} | {pred_str} | {cm_str} | {bias_str} |"
        )

    sep = "|:" + ":|:".join(["---"] * len(headers)) + ":|"
    header_line = "| " + " | ".join(headers) + " |"
    return "\n".join([header_line, sep] + rows)


def render_feature_importance_comparison_table(
    audit: FeatureUsefulnessAudit,
    top_n: int = 15,
) -> str:
    """Format comparative top feature importances between XGBoost and LightGBM."""
    lines = [
        "| Rank | XGBoost Feature | Weight | LightGBM Feature | Split Count |",
        "|:---:|:---|:---:|:---|:---:|",
    ]
    top_xgb = audit.top_xgboost_features[:top_n]
    top_lgb = audit.top_lightgbm_features[:top_n]
    max_len = max(len(top_xgb), len(top_lgb))

    for r in range(max_len):
        xgb_feat = top_xgb[r][0] if r < len(top_xgb) else "-"
        xgb_score = f"{top_xgb[r][1]:.0f}" if r < len(top_xgb) else "-"
        lgb_feat = top_lgb[r][0] if r < len(top_lgb) else "-"
        lgb_score = f"{top_lgb[r][1]:.0f}" if r < len(top_lgb) else "-"
        lines.append(f"| {r + 1} | `{xgb_feat}` | {xgb_score} | `{lgb_feat}` | {lgb_score} |")

    return "\n".join(lines)


def render_collinearity_table(audit: FeatureUsefulnessAudit, limit: int = 20) -> str:
    """Format high correlation pairs as Markdown table."""
    lines = [
        f"| Feature A | Feature B | Pearson Correlation (Threshold >= {audit.correlation_threshold:.2f}) |",
        "|:---|:---|:---:|",
    ]
    for p in audit.high_correlation_pairs[:limit]:
        lines.append(f"| `{p.feature_a}` | `{p.feature_b}` | {p.correlation:+.4f} |")
    if len(audit.high_correlation_pairs) > limit:
        lines.append(f"| ... and {len(audit.high_correlation_pairs) - limit} more pairs | - | - |")
    return "\n".join(lines)
