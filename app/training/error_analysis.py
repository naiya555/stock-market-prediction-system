"""Model Error Analysis and Feature Usefulness Audit Layer for Day 21.

Provides leakage-safe walk-forward error decomposition, class-specific (UP vs DOWN)
metrics, fold distribution shift diagnostics, collinearity clustering, and exploratory
tree feature importance diagnostics strictly computed on training data.
"""

